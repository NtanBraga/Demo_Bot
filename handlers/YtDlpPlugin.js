const { PlayableExtractorPlugin, Playlist, Song, DisTubeError } = require("distube");
const { spawn } = require("child_process");
const path = require("path");
const fs = require("fs");
const { metadataCache, streamUrlCache, singleFlight } = require("./Cache");

function resolveBinaryPath() {
  const localBinary = path.join(
    __dirname,
    "..",
    "node_modules",
    "@distube",
    "yt-dlp",
    "bin",
    process.platform === "win32" ? "yt-dlp.exe" : "yt-dlp"
  );
  if (fs.existsSync(localBinary)) {
    return localBinary;
  }
  return "yt-dlp";
}

function cleanYoutubeUrl(rawUrl) {
  if (typeof rawUrl !== "string") return rawUrl;
  try {
    const parsed = new URL(rawUrl);
    // If it is a YouTube video URL with Mix/Radio or autogenerated playlist parameters attached
    if (parsed.pathname === "/watch" && parsed.searchParams.has("v")) {
      const list = parsed.searchParams.get("list");
      if (
        !list 
        // ||
        // list.startsWith("RD") ||
        // list.startsWith("LL") ||
        // list.startsWith("FL") ||
        // parsed.searchParams.get("start_radio") === "1"
      ) {
        parsed.searchParams.delete("list");
        parsed.searchParams.delete("start_radio");
        parsed.searchParams.delete("index");
        return parsed.toString();
      }
    }
    return rawUrl;
  } catch {
    return rawUrl;
  }
}

function fetchFastStreamUrl(rawUrl) {
  const url = cleanYoutubeUrl(rawUrl);
  const cached = streamUrlCache.get(url) || streamUrlCache.get(rawUrl);
  if (cached) {
    return Promise.resolve(cached);
  }

  return singleFlight.do(`stream:${url}`, () => {
    const binary = resolveBinaryPath();
    const rootCookies = path.join(__dirname, "..", "cookies.txt");
    const cookieFlags = fs.existsSync(rootCookies) ? ["--cookies", rootCookies] : [];

    const flags = [
      "-g",
      "--no-warnings",
      "--no-check-certificates",
      "--no-playlist",
      "-f",
      "ba/ba*",
      "--extractor-args",
      "youtube:player_client=android;player_skip=webpage,configs",
      ...cookieFlags,
      url,
    ];

    return new Promise((resolve, reject) => {
      const startTime = Date.now();
      const proc = spawn(binary, flags);
      let stdout = "";
      let stderr = "";

      proc.stdout.on("data", (chunk) => {
        stdout += chunk;
      });
      proc.stderr.on("data", (chunk) => {
        stderr += chunk;
      });

      proc.on("close", (code) => {
        const streamUrl = stdout.trim().split("\n")[0]?.trim();
        if (code === 0 && streamUrl && streamUrl.startsWith("http")) {
          streamUrlCache.set(url, streamUrl);
          streamUrlCache.set(rawUrl, streamUrl);
          resolve(streamUrl);
        } else {
          console.error(`[yt-dlp fast stream error] Code: ${code}, Stderr: ${stderr || stdout}`);
          reject(new Error(stderr || stdout || `yt-dlp exited with code ${code}`));
        }
      });

      proc.on("error", (err) => {
        console.error(`[yt-dlp spawn error]:`, err);
        reject(err);
      });
    });
  });
}

